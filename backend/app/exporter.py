"""Exports generated test cases as a standalone pytest-playwright test file."""

import re

from .models import Step, TestCase

HEADER = '''"""Generated by WebSentinel-AI.

Run with:
    pip install pytest-playwright && playwright install chromium
    pytest {filename}
"""
import re

from playwright.sync_api import Page, expect

'''


def slug(title: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "_", title.lower()).strip("_")
    return s[:60] or "case"


def step_code(step: Step) -> list[str]:
    css = repr(step.target.css) if step.target else "''"
    v = repr(step.value)
    lines = [f"# {step.description}"] if step.description else []
    match step.action:
        case "goto":
            lines.append(f"response = page.goto({v})")
        case "fill":
            lines.append(f"page.locator({css}).first.fill({v})")
        case "click":
            lines += [f"page.locator({css}).first.click()", 'page.wait_for_load_state("load")']
        case "press":
            lines.append(f"page.locator({css}).first.press({v or repr('Enter')})")
        case "expect_visible":
            lines.append(f"expect(page.locator({css}).first).to_be_visible()")
        case "expect_text":
            lines.append(f'expect(page.locator("body")).to_contain_text({v})')
        case "expect_no_text":
            lines.append(f'expect(page.locator("body")).not_to_contain_text({v})')
        case "expect_url_contains":
            lines.append(f"expect(page).to_have_url(re.compile(re.escape({v})))")
        case "expect_url_not_contains":
            lines.append(f"expect(page).not_to_have_url(re.compile(re.escape({v})))")
        case "expect_title_contains":
            lines.append(f"expect(page).to_have_title(re.compile(re.escape({v})))")
        case "expect_status_ok":
            lines.append('assert page.evaluate("document.title") is not None')
            lines.append("assert response is None or response.status < 400")
    return lines


def export_pytest(tests: list[TestCase], filename: str = "test_generated.py") -> str:
    out = [HEADER.format(filename=filename)]
    used: set[str] = set()
    for test in tests:
        name = slug(test.title)
        while name in used:
            name += "_"
        used.add(name)
        out.append(f"def test_{name}(page: Page):")
        out.append(f"    # {test.title} [{test.category}/{test.severity}]")
        out.append("    response = None")
        for step in test.steps:
            out += [f"    {line}" for line in step_code(step)]
        out.append("")
        out.append("")
    return "\n".join(out).rstrip() + "\n"
